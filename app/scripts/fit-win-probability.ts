// Fits the in-game win probability model from MoneyPuck shots and writes its
// coefficients to src/server/api/win-probability-model.ts.
//
//   npx tsx scripts/fit-win-probability.ts [--write]
//
// Every shot is a game state (time, score, manpower) with a known result.
// States are aggregated in SQL (a few thousand rows leave the database),
// fitted on 2008-2024 and checked on 2025. Read-only.
import { writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { config } from "dotenv";
import pg from "pg";
import { regulationFeatures, OT_FEATURES } from "@/server/api/win-probability";
import { evaluate, fit } from "@/server/projections/logistic-fit";

config({ path: [".env.local", "../.env.local"], quiet: true });

const { values } = parseArgs({ options: { write: { type: "boolean", default: false } } });
const TEST_SEASON = 2025;

interface StateRow {
  season_group: "train" | "test";
  ot: boolean;
  remaining: number;
  diff: number;
  pp: number;
  en: number;
  n: number;
  wins: number;
}

// Remaining regulation time in 30 s buckets; goal difference capped at ±5.
const SQL = `
with states as (
  select
    case when season = ${TEST_SEASON} then 'test' else 'train' end as season_group,
    period = 4 as ot,
    case when period <= 3 then greatest(0, 3600 - game_time_seconds) / 30 * 30 + 15 else 0 end as remaining,
    greatest(-5, least(5, home_team_goals - away_team_goals)) as diff,
    sign((home_skaters_on_ice - home_empty_net::int) - (away_skaters_on_ice - away_empty_net::int)) as pp,
    home_empty_net::int - away_empty_net::int as en,
    home_team_won
  from shots
  where not is_playoff_game and period <= 4 and season <= ${TEST_SEASON}
    and home_skaters_on_ice between 3 and 6 and away_skaters_on_ice between 3 and 6
)
select season_group, ot, remaining, diff, pp, en, count(*)::int as n, sum(home_team_won::int)::int as wins
from states
group by 1, 2, 3, 4, 5, 6`;

const sigmoid = (z: number) => 1 / (1 + Math.exp(-z));

const url = process.env.DATABASE_URL_UNPOOLED ?? process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL is not set");
const client = new pg.Client({ connectionString: url, options: "-c default_transaction_read_only=on" });
await client.connect();
const { rows } = await client.query<StateRow>(SQL);
await client.end();
console.log(`${rows.length} aggregated state rows`);

const reg = (group: string) => rows.filter((r) => r.season_group === group && !r.ot);
const ot = (group: string) => rows.filter((r) => r.season_group === group && r.ot && r.diff === 0);

const regulation = fit(reg("train").map((r) => ({ x: regulationFeatures(r.remaining, r.diff, r.pp, r.en), n: r.n, wins: r.wins })));
const overtime = fit(ot("train").map((r) => ({ x: OT_FEATURES(r.pp), n: r.n, wins: r.wins })));

const predictReg = (r: StateRow) => sigmoid(regulationFeatures(r.remaining, r.diff, r.pp, r.en).reduce((s, v, i) => s + v * regulation[i], 0));
const predictOt = (r: StateRow) => sigmoid(OT_FEATURES(r.pp).reduce((s, v, i) => s + v * overtime[i], 0));
evaluate("Train, regulation", reg("train").map((r) => ({ p: predictReg(r), n: r.n, wins: r.wins })));
evaluate(`Test ${TEST_SEASON}, regulation`, reg("test").map((r) => ({ p: predictReg(r), n: r.n, wins: r.wins })));
evaluate(`Test ${TEST_SEASON}, overtime`, ot("test").map((r) => ({ p: predictOt(r), n: r.n, wins: r.wins })));

// Spot checks against the raw rates.
for (const [remaining, diff] of [[3585, 0], [1815, 1], [615, 1], [195, 1], [195, -1], [195, 2]] as const) {
  const raw = reg("train").filter((r) => r.remaining === remaining && r.diff === diff && r.pp === 0 && r.en === 0);
  const n = raw.reduce((s, r) => s + r.n, 0);
  const actual = raw.reduce((s, r) => s + r.wins, 0) / n;
  const model = sigmoid(regulationFeatures(remaining, diff, 0, 0).reduce((s, v, i) => s + v * regulation[i], 0));
  console.log(`  ${Math.round(remaining / 60)} min left, home ${diff >= 0 ? "+" : ""}${diff}: model ${(model * 100).toFixed(1)}%, actual ${(actual * 100).toFixed(1)}% (${n} states)`);
}

const fmt = (b: number[]) => `[${b.map((v) => Number(v.toPrecision(6))).join(", ")}]`;
const source = `// Generated by scripts/fit-win-probability.ts from MoneyPuck shots
// (regular season, ${rows.length} aggregated states). Don't edit by hand.
// Features: see regulationFeatures and OT_FEATURES in win-probability.ts.
export const REGULATION_COEFFICIENTS = ${fmt(regulation)};
export const OVERTIME_COEFFICIENTS = ${fmt(overtime)};
`;
if (values.write) {
  writeFileSync(new URL("../src/server/api/win-probability-model.ts", import.meta.url), source);
  console.log("\nWrote src/server/api/win-probability-model.ts");
} else {
  console.log(`\n${source}\nRun with --write to save.`);
}
